#!/bin/bash
# Builds TailBridge.app with the system Swift toolchain. Runs fixture tests first.
# Never installs anything and never touches network settings.
set -euo pipefail
cd "$(dirname "$0")"
OUT=build
APP="$OUT/TailBridge.app"
SWIFTC=(xcrun swiftc -swift-version 5 -O)
/bin/mkdir -p "$OUT"

# Version, build number and channel come only from version.conf. Each key exactly once, strictly validated.
conf() {
    local v
    [ "$(/usr/bin/grep -c "^$1=" version.conf)" = 1 ] || { echo "version.conf: $1 musi wystąpić dokładnie raz" >&2; exit 1; }
    v=$(/usr/bin/sed -n "s/^$1=//p" version.conf)
    [[ $v =~ ^$2$ ]] || { echo "version.conf: niepoprawne $1='$v'" >&2; exit 1; }
    printf '%s' "$v"
}
VERSION=$(conf VERSION '[0-9]+\.[0-9]+\.[0-9]+')
BUILD=$(conf BUILD '[1-9][0-9]{0,8}')
CHANNEL=$(conf CHANNEL '[A-Za-z]+')

# Source state: commit and whether the tree has uncommitted changes (build/ is ignored).
COMMIT=unknown DIRTY=unknown
if /usr/bin/git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
    COMMIT=$(/usr/bin/git rev-parse --verify HEAD)
    # Only a successful git status may report a clean or modified tree; a failure leaves DIRTY=unknown.
    if GIT_STATUS=$(/usr/bin/git status --porcelain); then
        if [ -z "$GIT_STATUS" ]; then DIRTY=no; else DIRTY=yes; fi
    fi
fi
[[ $COMMIT =~ ^([0-9a-f]{40}|unknown)$ ]] || { echo "nieoczekiwany commit: $COMMIT" >&2; exit 1; }
case $DIRTY in yes) DIRTY_PLIST='<true/>' ;; no) DIRTY_PLIST='<false/>' ;; *) DIRTY_PLIST='<string>unknown</string>' ;; esac
echo "== TailBridge $VERSION ($BUILD) $CHANNEL, commit $COMMIT, niezacommitowane zmiany: $DIRTY"

echo '== testy'
"${SWIFTC[@]}" -o "$OUT/tailbridge-tests" src/Core/*.swift tests/main.swift
"$OUT/tailbridge-tests"

echo '== testy prezentacji'
"${SWIFTC[@]}" -o "$OUT/tailbridge-ui-tests" src/Core/*.swift src/App/Checks.swift src/App/Presentation.swift \
    src/App/Strings.swift tests/app/main.swift -framework AppKit -framework Network
"$OUT/tailbridge-ui-tests"

echo '== pomocnik'
"${SWIFTC[@]}" -o "$OUT/com.tailbridge.helper" src/Core/*.swift src/Helper/main.swift

echo '== aplikacja'
"${SWIFTC[@]}" -o "$OUT/TailBridge" src/Core/*.swift src/App/*.swift -framework AppKit -framework Network

echo '== ikona'
"${SWIFTC[@]}" -o "$OUT/make-icon" tools/make-icon.swift
/bin/rm -rf "$OUT/AppIcon.iconset"
"$OUT/make-icon" "$OUT/AppIcon.iconset"
/usr/bin/iconutil -c icns -o "$OUT/AppIcon.icns" "$OUT/AppIcon.iconset"

/bin/rm -rf "$APP" "$OUT/BUILDINFO.txt"
/bin/mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
/bin/cp "$OUT/TailBridge" "$APP/Contents/MacOS/TailBridge"
/bin/cp "$OUT/com.tailbridge.helper" "$APP/Contents/Resources/com.tailbridge.helper"
/bin/cp -R src/App/Resources/ "$APP/Contents/Resources/"
/bin/cp "$OUT/AppIcon.icns" "$APP/Contents/Resources/AppIcon.icns"
# TB* keys feed the About panel. TBSigning describes what this script does below: ad-hoc only.
/bin/cat > "$APP/Contents/Info.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>CFBundleIdentifier</key><string>local.tailbridge.app</string>
	<key>CFBundleName</key><string>TailBridge</string>
	<key>CFBundleDisplayName</key><string>TailBridge</string>
	<key>CFBundleExecutable</key><string>TailBridge</string>
	<key>CFBundleIconFile</key><string>AppIcon</string>
	<key>CFBundlePackageType</key><string>APPL</string>
	<key>CFBundleInfoDictionaryVersion</key><string>6.0</string>
	<key>CFBundleShortVersionString</key><string>$VERSION</string>
	<key>CFBundleVersion</key><string>$BUILD</string>
	<key>TBChannel</key><string>$CHANNEL</string>
	<key>TBGitCommit</key><string>$COMMIT</string>
	<key>TBGitDirty</key>$DIRTY_PLIST
	<key>TBSigning</key><string>ad-hoc</string>
	<key>LSMinimumSystemVersion</key><string>13.0</string>
	<key>CFBundleDevelopmentRegion</key><string>en</string>
	<key>NSHighResolutionCapable</key><true/>
</dict>
</plist>
EOF
/usr/bin/plutil -lint -s "$APP/Contents/Info.plist"
/usr/bin/codesign --force --sign - "$APP/Contents/Resources/com.tailbridge.helper"
/usr/bin/codesign --force --sign - "$APP"
/usr/bin/codesign --verify --strict --deep "$APP"

# BUILDINFO sits next to the bundle (inside it would change the hashes it lists).
sha() { /usr/bin/shasum -a 256 "$1" | /usr/bin/cut -c1-64; }
CDHASH=$(/usr/bin/codesign -dvvv "$APP" 2>&1 | /usr/bin/sed -n 's/^CDHash=//p' | /usr/bin/head -1)
MANIFEST=$(tools/bundle-manifest.sh "$APP")  # a failure stops the build (set -e), never an empty field
{
    echo "# TailBridge BUILDINFO — generated by build.sh"
    echo "name=TailBridge"
    echo "bundle_id=local.tailbridge.app"
    echo "version=$VERSION"
    echo "build=$BUILD"
    echo "channel=$CHANNEL"
    echo "commit=$COMMIT"
    echo "uncommitted_changes=$DIRTY"
    echo "built_at_utc=$(/bin/date -u +%Y-%m-%dT%H:%M:%SZ)"
    echo "swiftc=$(xcrun swiftc --version 2>&1 | /usr/bin/head -1)"
    echo "sdk=macosx $(xcrun --show-sdk-version)"
    echo "developer_dir=$(/usr/bin/xcode-select -p)"
    echo "host=macOS $(/usr/bin/sw_vers -productVersion) ($(/usr/bin/sw_vers -buildVersion)) $(/usr/bin/uname -m)"
    echo "signature=ad-hoc (no Developer ID, not notarized; does not identify the publisher)"
    echo "cdhash=$CDHASH"
    echo "sha256_executable=$(sha "$APP/Contents/MacOS/TailBridge")"
    echo "sha256_helper=$(sha "$APP/Contents/Resources/com.tailbridge.helper")"
    echo "sha256_icon=$(sha "$APP/Contents/Resources/AppIcon.icns")"
    echo "sha256_info_plist=$(sha "$APP/Contents/Info.plist")"
    echo "bundle_manifest_sha256=$MANIFEST"
    echo "bundle_manifest_scope=directories (mode), regular files (mode, SHA-256); not xattrs, ACLs, owner, timestamps"
} > "$OUT/BUILDINFO.txt"

echo "== gotowe: $APP"
/bin/cat "$OUT/BUILDINFO.txt"
